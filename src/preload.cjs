const {contextBridge,ipcRenderer}=require('electron');
function subscribe(channel,callback){const listener=(_,data)=>callback(data);ipcRenderer.on(channel,listener);return()=>ipcRenderer.removeListener(channel,listener);}
contextBridge.exposeInMainWorld('icey',{
  getState:()=>ipcRenderer.invoke('state:get'),
  openPanel:tab=>ipcRenderer.invoke('panel:open',tab),
  windowAction:action=>ipcRenderer.invoke('window:action',action),
  petMenu:()=>ipcRenderer.invoke('pet:menu'),
  saveSettings:settings=>ipcRenderer.invoke('settings:save',settings),
  saveTasks:tasks=>ipcRenderer.invoke('tasks:save',tasks),
  switchWorkspace:id=>ipcRenderer.invoke('workspace:switch',id),
  saveWorkspace:value=>ipcRenderer.invoke('workspace:save',value),
  chooseWorkspaceFolder:()=>ipcRenderer.invoke('workspace:choose-folder'),
  archiveWorkspace:(id,archived)=>ipcRenderer.invoke('workspace:archive',id,archived),
  runTaskNow:id=>ipcRenderer.invoke('tasks:run-now',id),
  readTaskResult:id=>ipcRenderer.invoke('tasks:read-result',id),
  chat:(message,options)=>ipcRenderer.invoke('chat:send',message,options),
  resolveAction:(id,approve)=>ipcRenderer.invoke('action:resolve',id,approve),
  listScreens:()=>ipcRenderer.invoke('screen:list'),
  previewScreen:id=>ipcRenderer.invoke('screen:preview',id),
  pauseAwareness:()=>ipcRenderer.invoke('awareness:pause'),
  editMemory:(id,text)=>ipcRenderer.invoke('memory:edit',id,text),
  deleteMemory:id=>ipcRenderer.invoke('memory:delete',id),
  resetMemory:()=>ipcRenderer.invoke('memory:reset'),
  reviewMemory:()=>ipcRenderer.invoke('memory:review'),
  deleteMemoryReview:week=>ipcRenderer.invoke('memory:review-delete',week),
  synthesize:text=>ipcRenderer.invoke('voice:synthesize',text),
  cancelVoice:()=>ipcRenderer.invoke('voice:cancel'),
  testVoice:()=>ipcRenderer.invoke('voice:test'),
  clearChat:()=>ipcRenderer.invoke('chat:clear'),
  selectFiles:()=>ipcRenderer.invoke('files:select'),
  clearFiles:()=>ipcRenderer.invoke('files:clear'),
  trashFiles:ids=>ipcRenderer.invoke('files:trash',ids),
  demoShred:()=>ipcRenderer.invoke('pet:demo'),
  openFolder:name=>ipcRenderer.invoke('folder:open',name),
  openExtensionGuide:()=>ipcRenderer.invoke('extensions:guide'),
  preparePlugin:(mode,value)=>ipcRenderer.invoke('extensions:prepare',mode,value),
  choosePlugin:()=>ipcRenderer.invoke('extensions:choose'),
  installPlugin:id=>ipcRenderer.invoke('extensions:install',id),
  discardPlugin:id=>ipcRenderer.invoke('extensions:discard',id),
  managePlugin:(id,operation)=>ipcRenderer.invoke('extensions:manage',id,operation),
  inspectPlugin:id=>ipcRenderer.invoke('extensions:inspect',id),
  exportPlugin:id=>ipcRenderer.invoke('extensions:export',id),
  hover:value=>ipcRenderer.send('pet:hover',!!value),
  drag:phase=>ipcRenderer.send('pet:drag',phase),
  onState:callback=>subscribe('state:changed',callback),
  onTab:callback=>subscribe('panel:tab',callback),
  onSay:callback=>subscribe('pet:say',callback),
  onShred:callback=>subscribe('pet:shred',callback)
});
